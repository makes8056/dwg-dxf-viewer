/**
 * 同じ部品を、4通りの置き方で並べた見本を作る。
 *
 * 部品の中身は、**裏返すと必ず形が変わるもの**だけにしてある。
 *   円弧 … 右上へふくらむ（0→90度）。裏返すとふくらむ向きが変わる
 *   縦線 … 上へ伸びる。上下に裏返すと下へ向く
 *   文字 … 水平。左右に裏返すと180度になる
 *
 * 円だけ、正方形だけ、のような**裏返しても同じに見えるもの**を見本にすると、
 * 間違っていても気づけない。
 */
function 鏡像の見本() {
  const 部品 = [
    [0, 'ARC'], [8, '0'], [62, 256], [10, 0], [20, 0], [40, 10], [50, 0], [51, 90],
    [0, 'LINE'], [8, '0'], [62, 256], [10, 0], [20, 0], [11, 0], [21, 20],
    [0, 'TEXT'], [8, '0'], [62, 256], [10, 0], [20, 0], [40, 5], [50, 0], [1, 'R'],
    // 45度に傾いた文字。裏返したときに「読める向きへ倒す」が効いているかを見る。
    // 水平の文字だけだと、倒す処理が無くても同じ結果になってしまい、確かめられない
    [0, 'TEXT'], [8, '0'], [62, 256], [10, 0], [20, -15], [40, 5], [50, 45], [1, 'K'],
  ];
  const 組 = 前置き('鏡像の見本：同じ部品を、ふつう・左右反転・上下反転・押し出しZ=-1 で並べた');
  組.push([0, 'SECTION'], [2, 'BLOCKS']);
  組.push([0, 'BLOCK'], [2, 'P'], [10, 0], [20, 0], [30, 0], ...部品, [0, 'ENDBLK']);
  組.push([0, 'ENDSEC']);

  組.push([0, 'SECTION'], [2, 'ENTITIES']);
  // ① ふつう
  組.push([0, 'INSERT'], [8, '0'], [62, 256], [2, 'P'], [10, 0], [20, 0]);
  // ② 左右の鏡像（Xの拡大率がマイナス）
  組.push([0, 'INSERT'], [8, '0'], [62, 256], [2, 'P'], [10, 100], [20, 0], [41, -1], [42, 1]);
  // ③ 上下の鏡像（Yの拡大率がマイナス）
  組.push([0, 'INSERT'], [8, '0'], [62, 256], [2, 'P'], [10, 200], [20, 0], [41, 1], [42, -1]);
  // ④ 押し出しZが-1。置く点も裏側で書かれるので、-300 が +300 に出る
  組.push([0, 'INSERT'], [8, '0'], [62, 256], [2, 'P'], [10, -300], [20, 0], [230, -1]);
  組.push([0, 'ENDSEC'], [0, 'EOF']);
  return dxf(組);
}

