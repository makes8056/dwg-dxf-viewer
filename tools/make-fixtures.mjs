// 34章：レイヤーの色がマイナス（DWGから変換したDXFで起きる）
// ============================================================
function レイヤーの見本(色たち, 説明) {
  const レイヤー名 = ['0', 'PIPE', 'DIM'];
  const 組 = 前置き(説明, 色たち, レイヤー名);
  組.push([0, 'SECTION'], [2, 'ENTITIES']);
  レイヤー名.forEach((名, i) => {
    組.push(
      [0, 'LINE'], [8, 名], [62, 256],
      [10, 0], [20, i * 10], [11, 100], [21, i * 10]
    );
  });
  組.push([0, 'ENDSEC'], [0, 'EOF']);
  return dxf(組);
}

