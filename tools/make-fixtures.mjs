/**
 * 引出線の見本を作る。
 *
 * 中身は かっこ で囲まれた入れ子になっている。
 *   CONTEXT_DATA{ … LEADER{ … LEADER_LINE{ … } } }
 *
 * **コード304は「文字の中身」と「LEADER_LINE{」の両方に使われる。**
 * 番号だけで見分けると、区切りの記号が文字として図面に出てしまう。
 * この見本は、その取り違えが起きたらテストで分かるように作ってある。
 */
function 引出線の見本() {
  const 組 = 前置き('引出線（MULTILEADER）の見本。折れ線と文字に直して描く');
  組.push([0, 'SECTION'], [2, 'ENTITIES']);
  組.push(
    [0, 'MULTILEADER'], [8, '0'], [62, 7],
    [300, 'CONTEXT_DATA{'],
    [40, 1.0], // 全体の拡大率（重ねて掛けない）
    [10, 0.0], [20, 0.0], // 中身の基点（使わない）
    [41, 5.0], // 文字の高さ
    [304, 'VP50'], // 文字の中身
    [12, 100.0], [22, 50.0], // 文字を置く場所
    [13, 1.0], [23, 0.0], // 文字の向き（右向き＝0度）
    [302, 'LEADER{'],
    [10, 90.0], [20, 50.0], // 引出線の終わりの点
    [11, 1.0], [21, 0.0], // 折れ曲がってから伸びる向き
    [40, 10.0], // その長さ
    [304, 'LEADER_LINE{'], // ← 文字ではなく区切り。ここが落とし穴
    [10, 0.0], [20, 0.0],
    [10, 50.0], [20, 25.0],
    [10, 90.0], [20, 50.0],
    [305, '}'],
    [303, '}'],
    [301, '}']
  );
  組.push([0, 'ENDSEC'], [0, 'EOF']);
  return dxf(組);
}

