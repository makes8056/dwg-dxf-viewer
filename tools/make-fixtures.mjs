import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 出力先 = path.join(ROOT, 'tests', 'fixtures');

/** コードと値の組を、DXFの文字にする（必ず2行1組にする）。 */
function dxf(組) {
  return 組.map(([code, value]) => `${code}\n${value}`).join('\n') + '\n';
}

/** ヘッダーとTABLES（レイヤー）を作る。 */
function 前置き(説明, 色たち = [7], レイヤー名 = ['0']) {
  const 組 = [
    [999, 説明],
    [0, 'SECTION'], [2, 'HEADER'],
    [9, '$ACADVER'], [1, 'AC1015'],
    [0, 'ENDSEC'],
    [0, 'SECTION'], [2, 'TABLES'],
    [0, 'TABLE'], [2, 'LAYER'], [70, 色たち.length],
  ];
  色たち.forEach((色, i) => 組.push([0, 'LAYER'], [2, レイヤー名[i]], [70, 0], [62, 色]));
  組.push([0, 'ENDTAB'], [0, 'ENDSEC']);
  return 組;
}

