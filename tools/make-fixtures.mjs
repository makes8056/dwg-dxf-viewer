/**
 * 自由曲線の見本を作る。
 *
 * 【なぜ半円にするか】
 *   重み（41）付きの3点・次数2の曲線は、**数学的にぴったりの円弧**になる。
 *   だからテスト側で「中心からの距離が半径どおりか」を1点ずつ検算できる。
 *   目で見て「それらしい」ではなく、数字で正しさを押さえられる見本にした。
 *
 *   制御点 (100,0) (100,100) (0,100)、真ん中の重みだけ cos45度 にすると、
 *   原点中心・半径100の四分円になる。
 */
function 自由曲線の見本() {
  const 組 = 前置き('自由曲線（SPLINE）の見本。重み付きで、原点中心・半径100の四分円になる');
  組.push([0, 'SECTION'], [2, 'ENTITIES']);

  // (1) 重み付き・次数2 … ぴったり四分円になる（テストで半径を検算する）
  組.push(
    [0, 'SPLINE'], [8, '0'], [62, 7],
    [70, 8], // 8 = 平面上の曲線
    [71, 2], // 次数2
    [72, 6], // ノットの数 ＝ 制御点3 ＋ 次数2 ＋ 1
    [73, 3], // 制御点の数
    [74, 0], // 通過点は無し
    [40, 0], [40, 0], [40, 0], [40, 1], [40, 1], [40, 1],
    [41, 1], [41, Math.cos(Math.PI / 4)], [41, 1],
    [10, 100], [20, 0], [30, 0],
    [10, 100], [20, 100], [30, 0],
    [10, 0], [20, 100], [30, 0]
  );

  // (2) ノットが1つも書かれていない壊れた曲線。
  //     それでも捨てずに描けること（両端の制御点は必ず通る）を確かめる
  組.push(
    [0, 'SPLINE'], [8, '0'], [62, 7],
    [70, 8], [71, 3], [72, 0], [73, 4], [74, 0],
    [10, 0], [20, 200], [30, 0],
    [10, 30], [20, 260], [30, 0],
    [10, 70], [20, 260], [30, 0],
    [10, 100], [20, 200], [30, 0]
  );

  // (3) 制御点が無く、通過点だけの曲線。
  //     なめらかさは出ないが、通過点をつないで必ず何か出す
  組.push(
    [0, 'SPLINE'], [8, '0'], [62, 7],
    [70, 8], [71, 3], [72, 0], [73, 0], [74, 3],
    [11, 0], [21, 400], [31, 0],
    [11, 50], [21, 450], [31, 0],
    [11, 100], [21, 400], [31, 0]
  );

  組.push([0, 'ENDSEC'], [0, 'EOF']);
  return dxf(組);
}

